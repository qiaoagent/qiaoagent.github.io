#!/usr/bin/env python3
"""Build the paper directory from the existing HTML pages, using the bio index layout."""
import html
from html.parser import HTMLParser
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit


HERE = Path(__file__).resolve().parent
TEMPLATE = HERE.parent / 'bio' / 'index.html'
DISPLAY_NAMES = {
    'Agents-Last-Exam': 'Agents’ Last Exam',
    'AIScientist': 'Risks of AI Scientists',
    'HiddenFlaws': 'Hidden Flaws',
    'PubMed-and-Beyond': 'PubMed and Beyond',
    'PubTator-3': 'PubTator 3.0',
    'Retrieve-Summarize-Verify': 'Retrieve, Summarize, and Verify',
    'TrialGPT-2': 'TrialGPT 2.0',
}


class HeroParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.in_hero = False
        self.field = None
        self.title = []
        self.venue = []
        self.pdf = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        classes = attrs.get('class', '').split()
        if tag == 'header' and 'hero' in classes:
            self.in_hero = True
        if not self.in_hero:
            return
        if tag == 'h1':
            self.field = 'title'
        elif tag == 'div' and 'venue' in classes:
            self.field = 'venue'
        elif tag == 'a' and 'primary' in classes:
            self.pdf = attrs.get('href')

    def handle_data(self, data):
        if self.in_hero and self.field:
            getattr(self, self.field).append(data)

    def handle_endtag(self, tag):
        if (tag == 'h1' and self.field == 'title') or (tag == 'div' and self.field == 'venue'):
            self.field = None
        if tag == 'header':
            self.in_hero = False
            self.field = None


def require_asset(url, page):
    if not url:
        raise ValueError('{}: missing PDF link'.format(page.name))
    parsed = urlsplit(url)
    if parsed.scheme or parsed.netloc:
        return
    path = unquote(parsed.path)
    target = HERE.parent / path.lstrip('/') if path.startswith('/') else HERE / path
    if not target.is_file():
        raise ValueError('{}: missing asset {}'.format(page.name, url))


def read_paper(path):
    parser = HeroParser()
    parser.feed(path.read_text(encoding='utf-8'))
    title = ' '.join(''.join(parser.title).split())
    venue = ' '.join(''.join(parser.venue).split())
    if not title or not venue:
        raise ValueError('{}: missing title or venue'.format(path.name))
    require_asset(parser.pdf, path)
    return {
        'name': DISPLAY_NAMES.get(path.stem, path.stem),
        'title': title,
        'venue': venue,
        'page': path.name,
        'pdf': parser.pdf,
    }


def render_row(paper):
    name, title, venue, page, pdf = (
        html.escape(paper[key], quote=True)
        for key in ('name', 'title', 'venue', 'page', 'pdf')
    )
    return (
        '      <li>\n'
        f'        <h2 class="name" title="{title}">{name}</h2>\n'
        f'        <div class="meta">{venue}</div>\n'
        '        <div class="links">'
        f'<a href="{page}" aria-label="{name}: HTML summary">HTML</a>'
        f'<a href="{pdf}" target="_blank" rel="noopener" aria-label="{name}: PDF">PDF</a>'
        '</div>\n'
        '      </li>'
    )


def build():
    papers = [read_paper(path) for path in HERE.glob('*.html') if path.name != 'index.html']
    papers.sort(key=lambda paper: paper['name'].casefold())
    if not papers:
        raise ValueError('No paper pages found')
    page = TEMPLATE.read_text(encoding='utf-8')
    page, count = re.subn(r'<title>.*?</title>', '<title>Qiao Jin | Papers</title>', page, count=1)
    assert count == 1, 'Bio template has no page title'
    page, count = re.subn(r'<h1>.*?</h1>', '<h1>Papers</h1>', page, count=1)
    assert count == 1, 'Bio template has no heading'
    lead = f'<p class="lead">{len(papers)} papers, with HTML summaries and PDFs.</p>'
    page, count = re.subn(r'<p class="lead">.*?</p>', lambda _: lead, page, count=1, flags=re.S)
    assert count == 1, 'Bio template has no introduction'
    rows = '    <ul aria-label="Paper directory">\n' + '\n'.join(map(render_row, papers)) + '\n    </ul>'
    page, count = re.subn(r'    <ul>.*?</ul>', lambda _: rows, page, count=1, flags=re.S)
    assert count == 1, 'Bio template has no directory list'
    page = page.replace('  <style>', '  <!-- Generated by paper/build.py; edit the individual paper pages. -->\n  <style>', 1)
    page = page.replace('  </style>', '''    li { display: grid; grid-template-columns: minmax(0, 1fr) auto auto; align-items: baseline; gap: 16px; padding: 12px 0; }
    .name { font-weight: 400; margin: 0; white-space: nowrap; overflow: hidden; text-overflow: ellipsis; }
    .meta { margin: 0; white-space: nowrap; }
    .links { display: flex; gap: 16px; margin: 0; white-space: nowrap; }
    .links a { margin-right: 0; }
    a:focus-visible { outline: 2px solid #b89a60; outline-offset: 4px; }
    @media (max-width: 600px) {
      li { grid-template-columns: minmax(0, 1fr) auto; gap: 12px; }
      .name { font-size: 1rem; }
      .meta { display: none; }
    }
  </style>''', 1)
    (HERE / 'index.html').write_text(page, encoding='utf-8')
    print('Built paper/index.html: {} papers'.format(len(papers)))


if __name__ == '__main__':
    build()
